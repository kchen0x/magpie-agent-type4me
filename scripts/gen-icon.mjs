// Writes icon.js from assets/icon.png as a data: URL.
//
// magpie runs agent modules in moejs, which can't read files at run time,
// so the picture ships inside the module. Run after changing the PNG:
//
//   bun scripts/gen-icon.mjs

import { readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")
const png = readFileSync(join(root, "assets/icon.png"))

// magpie refuses pictures over 1 MiB (provider.MaxIcon)
if (png.length > 1 << 20) {
  throw new Error(`assets/icon.png is ${png.length} bytes; keep it under 1 MiB`)
}

const body =
  "// Generated by scripts/gen-icon.mjs from assets/icon.png. Do not edit.\n" +
  `export const icon = "data:image/png;base64,${png.toString("base64")}"\n`
writeFileSync(join(root, "icon.js"), body)
console.log(`icon.js: ${png.length} bytes of PNG`)
